"""Write ``docs/data_report.md`` describing the catalog and the synthetic benchmark."""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

import pyarrow.parquet as pq


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=Path("data/catalog.parquet"))
    parser.add_argument("--golden", type=Path, default=Path("data/golden_eval.jsonl"))
    parser.add_argument("--out", type=Path, default=Path("docs/data_report.md"))
    args = parser.parse_args()

    cat = pq.read_table(args.catalog).to_pylist()
    gold = [json.loads(x) for x in args.golden.read_text(encoding="utf-8").splitlines() if x]
    by_id = {r["sku_id"]: r for r in cat}

    brands = Counter(r["brand"] for r in cat)
    cats = Counter(r["category"] for r in cat)
    units = Counter(r["qty_unit"] for r in cat)
    multipacks = sum(1 for r in cat if r["qty_count"] > 1)
    name_len = [len(r["name"]) for r in cat]
    slices = Counter(g["slice"] for g in gold)
    splits = Counter((g["slice"], g["split"]) for g in gold)
    transforms: dict[str, Counter[str]] = {}
    for g in gold:
        transforms.setdefault(g["slice"], Counter()).update(g["transforms"])

    md: list[str] = [
        "# Data Report",
        "",
        "Generated by `scripts/data_report.py` (`make data`). Source: "
        "[Open Food Facts](https://world.openfoodfacts.org/data) Hugging Face Parquet dump "
        "(`openfoodfacts/product-database`, ODbL 1.0).",
        "",
        "## Catalog (`data/catalog.parquet`)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| SKUs | {len(cat):,} |",
        f"| Distinct brands | {len(brands):,} |",
        f"| Distinct leaf categories | {len(cats):,} |",
        f"| Mass (g) / volume (ml) SKUs | {units.get('g', 0):,} / {units.get('ml', 0):,} |",
        f"| Multipacks | {multipacks:,} |",
        f"| Name length median / max | {statistics.median(name_len):.0f} / {max(name_len)} |",
        "",
        "Selection: products tagged `en:germany`, valid EAN-8/13/14, German product name, "
        "brand, parseable mass/volume quantity and an English category tag; ranked by "
        "`unique_scans_n` (popularity) and de-duplicated on normalised "
        "`brand + name + quantity`.",
        "",
        "Top brands: " + ", ".join(f"{b} ({n})" for b, n in brands.most_common(12)),
        "",
        "Top categories: " + ", ".join(f"{c} ({n})" for c, n in cats.most_common(12)),
        "",
        "## Synthetic invoice benchmark (`data/golden_eval.jsonl`)",
        "",
        f"{len(gold):,} labelled `(invoice_line, sku_id, slice)` pairs, generator "
        "`skumatch.data.synth.InvoiceLineGenerator(seed=42)`. "
        "`split=dev` (~20%) is reserved for tuning fusion weights; all reported metrics use "
        "`split=test`.",
        "",
        "| Slice | Lines | dev | test | Most frequent transforms |",
        "|---|---|---|---|---|",
    ]
    for s in ("abbreviations", "unit_swap", "ocr_typos", "hard_negatives"):
        top = ", ".join(f"`{t}` ({n})" for t, n in transforms.get(s, Counter()).most_common(4))
        md.append(
            f"| `{s}` | {slices.get(s, 0)} | {splits.get((s, 'dev'), 0)} | "
            f"{splits.get((s, 'test'), 0)} | {top} |"
        )
    md += ["", "### Examples", "", "| Slice | Invoice line | Ground-truth SKU | Hard negative |"]
    md.append("|---|---|---|---|")
    seen: Counter[str] = Counter()
    for g in gold:
        if seen[g["slice"]] >= 4:
            continue
        seen[g["slice"]] += 1
        t = by_id[g["sku_id"]]
        neg = by_id.get(g.get("hard_negative_sku_id") or -1)
        neg_txt = f"{neg['brand']} — {neg['name']} {neg['quantity_raw']}" if neg else ""
        line = g["invoice_line"].replace("|", "\\|")
        md.append(
            f"| `{g['slice']}` | `{line}` | {t['brand']} — {t['name']} {t['quantity_raw']} "
            f"| {neg_txt} |"
        )
    md += [
        "",
        "## Reproducibility",
        "",
        "```bash",
        "make data   # uses committed data/catalog.parquet; SKUMATCH_REFETCH=1 rebuilds from OFF",
        "```",
        "",
        "The generator is pure-Python and seeded; `tests/unit/test_synth.py` asserts determinism.",
        "",
    ]
    args.out.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
