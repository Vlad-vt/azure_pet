"""EXPLAIN (ANALYZE, BUFFERS) each retriever and assert the intended index is used.

Writes ``docs/explain_analyze.md``. Exit code 1 if any retriever falls back to a seq scan.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path

from sqlalchemy import text

from skumatch.config import get_settings
from skumatch.db.session import build_engine
from skumatch.embeddings import OnnxEmbedder
from skumatch.normalize import normalize_for_search
from skumatch.normalize.text import normalize_for_embedding
from skumatch.retrieval.sql import build_tsquery

QUERY = "MILSA. Speisequark MAGERSTUFE 0,25 kg"

STATEMENTS = {
    "dense (HNSW, cosine)": (
        "SELECT id FROM skus ORDER BY embedding <=> CAST(:vec AS vector) LIMIT 50",
        "ix_skus_embedding_hnsw",
    ),
    "fts (GIN tsvector)": (
        "SELECT id, ts_rank_cd(search_tsv, to_tsquery('simple', :tsq), 1) AS s FROM skus "
        "WHERE search_tsv @@ to_tsquery('simple', :tsq) ORDER BY s DESC LIMIT 50",
        "ix_skus_search_tsv_gin",
    ),
    "trigram (GIN gin_trgm_ops)": (
        "SELECT id, similarity(search_text, :q) AS s FROM skus WHERE search_text % :q "
        "ORDER BY s DESC LIMIT 50",
        "ix_skus_search_text_trgm_gin",
    ),
}


async def run(out: Path) -> int:
    settings = get_settings()
    engine = build_engine(settings, url=settings.migration_url)
    embedder = OnnxEmbedder(settings.model_dir)
    vec = embedder.embed_one(normalize_for_embedding(QUERY))
    normalized = normalize_for_search(QUERY)
    params = {
        "vec": "[" + ",".join(f"{x:.6f}" for x in vec.tolist()) + "]",
        "tsq": build_tsquery(normalized),
        "q": normalized,
    }
    md = [
        "# EXPLAIN ANALYZE — retrieval queries",
        "",
        f"Query: `{QUERY}` → normalised `{normalized}`; tsquery `{params['tsq']}`.",
        "Generated by `make explain` (`scripts/explain.py`).",
        "",
    ]
    failures = 0
    async with engine.begin() as conn:
        count = (await conn.execute(text("SELECT count(*) FROM skus"))).scalar_one()
        md.insert(3, f"Catalog rows: {count}.")
        await conn.execute(text("SET LOCAL hnsw.ef_search = 80"))
        await conn.execute(text("SET LOCAL pg_trgm.similarity_threshold = 0.15"))
        for title, (sql, index) in STATEMENTS.items():
            plan_rows = await conn.execute(text(f"EXPLAIN (ANALYZE, BUFFERS) {sql}"), params)
            plan = "\n".join(r[0] for r in plan_rows)
            used = index in plan
            failures += 0 if used else 1
            md += [
                f"## {title}",
                "",
                f"Index `{index}` used: **{'yes' if used else 'NO'}**",
                "",
                "```text",
                plan,
                "```",
                "",
            ]
            print(f"{title:28} index_used={used}")
    await engine.dispose()
    await asyncio.to_thread(out.write_text, "\n".join(md), encoding="utf-8")
    print(f"wrote {out}")
    return 1 if failures else 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/explain_analyze.md"))
    args = parser.parse_args()
    sys.exit(asyncio.run(run(args.out)))


if __name__ == "__main__":
    main()
